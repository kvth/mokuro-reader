import { describe, expect, it } from 'vitest';
import { deinflect } from './deinflect';

const cases: [surface: string, base: string][] = [
  // ichidan
  ['食べた', '食べる'],
  ['食べて', '食べる'],
  ['食べない', '食べる'],
  ['食べなかった', '食べる'],
  ['食べます', '食べる'],
  ['食べました', '食べる'],
  ['食べませんでした', '食べる'],
  ['食べたい', '食べる'],
  ['食べたかった', '食べる'],
  ['食べている', '食べる'],
  ['食べていた', '食べる'],
  ['食べてる', '食べる'],
  ['食べちゃう', '食べる'],
  ['食べられる', '食べる'],
  ['食べさせられなかった', '食べる'],
  ['食べよう', '食べる'],
  ['食べれば', '食べる'],
  ['食べたら', '食べる'],
  ['食べながら', '食べる'],
  // godan
  ['書いた', '書く'],
  ['泳いで', '泳ぐ'],
  ['話した', '話す'],
  ['待って', '待つ'],
  ['死んだ', '死ぬ'],
  ['遊んで', '遊ぶ'],
  ['読んだ', '読む'],
  ['帰った', '帰る'],
  ['買って', '買う'],
  ['行った', '行く'],
  ['書かない', '書く'],
  ['分からん', '分かる'],
  ['書きます', '書く'],
  ['書こう', '書く'],
  ['書ける', '書く'],
  ['書けば', '書く'],
  ['書かれた', '書く'],
  ['書かせる', '書く'],
  ['読んでいる', '読む'],
  ['読んじゃった', '読む'],
  ['言われた', '言う'],
  // する / 来る
  ['勉強した', '勉強'],
  ['勉強しました', '勉強'],
  ['勉強している', '勉強'],
  ['来た', '来る'],
  ['来ない', '来る'],
  ['こない', 'くる'],
  ['きた', 'くる'],
  ['来られる', '来る'],
  // い-adjectives
  ['高かった', '高い'],
  ['高くない', '高い'],
  ['高くて', '高い'],
  ['高ければ', '高い'],
  ['高く', '高い'],
  ['高すぎる', '高い'],
  ['高そう', '高い']
];

describe('deinflect', () => {
  it.each(cases)('%s → %s', (surface, base) => {
    expect(deinflect(surface)).toContain(base);
  });

  it('keeps the surface form itself', () => {
    expect(deinflect('学校')).toEqual(['学校']);
  });

  it('never yields an intermediate form as a result', () => {
    // 食べ (the bare stem) is reached on the way, but is not a dictionary form
    expect(deinflect('食べました')).not.toContain('食べ');
    expect(deinflect('食べている')).not.toContain('食べて');
  });
});
